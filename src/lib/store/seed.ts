function vehicleById(id: string) {
  return vehicles.find((item) => item.id === id)!;
}
function driverById(id: string) {
  return drivers.find((item) => item.id === id)!;
}
function fuelById(id: string) {
  return fuelProviders.find((item) => item.id === id)!;
}

function makeTrip(
  partial: Omit<Trip, "costs" | "margin" | "geometry"> & { geometry?: [number, number][] },
): Trip {
  const evaluated = evaluateTrip(
    partial,
    vehicleById(partial.vehicleId),
    driverById(partial.driverId),
    fuelById(partial.fuelProviderId),
    company,
    fuelMarket,
  );
  const origin = partial.stops.find((stop) => stop.kind === "origin") ?? partial.stops[0];
  const dest = partial.stops.find((stop) => stop.kind === "destination") ?? partial.stops.at(-1);
  const geometry =
    partial.geometry ??
    (origin && dest
      ? [
          [origin.lat, origin.lng],
          [dest.lat, dest.lng],
        ]
      : []);
  return { ...partial, geometry, costs: evaluated.costs, margin: evaluated.margin };
}

